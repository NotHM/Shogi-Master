import { BoardScaleId, PlayerSide } from './shogiEngine';

export interface PuzzleStep {
  // Player's move (either board move from->to or drop code->to)
  type: 'move' | 'drop';
  fromR?: number;
  fromC?: number;
  dropCode?: string;
  toR: number;
  toC: number;
  secondToR?: number;
  secondToC?: number;
  promote?: boolean;
  // Defender AI's automatic reply after player makes this move (if multi-move Tsume!)
  defenderReply?: {
    fromR: number;
    fromC: number;
    toR: number;
    toC: number;
    explanation: string;
  };
}

